//! The needs list: what main needs the operator to decide. An item is a marked loop in
//! `workspace/life/open.md`, so open.md stays the one truth for reminders:
//!
//! `- [ ] 2026-11-05 · which plan to take · need now · detail needs/plan-choice.md · from: main`
//! `... · need on 2026-12-01 · detail needs/x.md · from: main`
//! `... · need when the quote arrives · detail needs/y.md · from: main`
//!
//! `workspace/life/needs/<slug>.md` holds the full detail and the one-line recommendation.
//! `workspace/life/needs.md` is a view generated from those two, never edited by hand.

use crate::core::{today_date, Ctx};
use crate::die;
use crate::error::R;
use crate::fm::{self, rx};
use crate::life::{self, vpath, TextFile};
use crate::open::{self, Loop, OpenDoc, OPEN_REL};
use crate::outln;
use crate::pyos;
use chrono::NaiveDate;
use clap::Subcommand;
use serde_json::{json, Value};

pub const VIEW_REL: &str = "workspace/life/needs.md";
pub const DETAIL_DIR_REL: &str = "workspace/life/needs";
pub const SECTION: &str = "Decisions needed";
const LIFE_REL: &str = "workspace/life";
const VIEW_HEAD: &str = "# What needs you\n\n<!-- Generated by af from the need lines in open.md; an edit here is overwritten. Change it with af needs. -->\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum When {
    Now,
    On(NaiveDate),
    Trigger(String),
}

impl When {
    fn field(&self) -> String {
        match self {
            When::Now => "now".to_string(),
            When::On(d) => format!("on {}", d.format("%Y-%m-%d")),
            When::Trigger(t) => format!("when {t}"),
        }
    }

    /// Whether it needs him now: a dated item does from its date on, by itself.
    pub fn is_now(&self, today: NaiveDate) -> bool {
        match self {
            When::Now => true,
            When::On(d) => *d <= today,
            When::Trigger(_) => false,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Need {
    pub when: When,
    /// Relative to `workspace/life/`: `needs/<slug>.md`.
    pub detail: String,
}

impl Need {
    fn detail_rel(&self) -> String {
        format!("{LIFE_REL}/{}", self.detail)
    }
}

/// Lifts the need fields off a loop line: the line without them, and the need. A line whose
/// fields are malformed comes back whole, and `parse_open` refuses its ` · need ` token.
pub fn split_need(line: &str) -> (String, Option<Need>) {
    let re = rx(
        r"\A(.*) · need (now|on \d{4}-\d{2}-\d{2}|when \S(?:.*?\S)?) · detail (needs/[a-z0-9][a-z0-9-]*\.md) · from: (.*)\z",
    );
    let Some(c) = re.captures(line) else {
        return (line.to_string(), None);
    };
    let field = &c[2];
    let when = if field == "now" {
        Some(When::Now)
    } else if let Some(d) = field.strip_prefix("on ") {
        NaiveDate::parse_from_str(d, "%Y-%m-%d").ok().map(When::On)
    } else {
        let t = &field["when ".len()..];
        (!t.contains(" · ")).then(|| When::Trigger(t.to_string()))
    };
    match when {
        Some(when) => (format!("{} · from: {}", &c[1], &c[4]), Some(Need { when, detail: c[3].to_string() })),
        None => (line.to_string(), None),
    }
}

pub fn format_line(opened: NaiveDate, text: &str, need: &Need, from: &str) -> String {
    format!("- [ ] {} · {text} · need {} · detail {} · from: {from}", opened.format("%Y-%m-%d"), need.when.field(), need.detail)
}

// ------------------------------------------------------------------ the items

/// A marked loop with what the view prints for it.
pub struct Item {
    pub l: Loop,
    pub need: Need,
    /// The detail file's `recommendation:`; None when the file or the field is missing.
    pub rec: Option<String>,
    pub detail_exists: bool,
}

fn recommendation(ctx: &Ctx, rel: &str) -> Option<String> {
    let tf = TextFile::load(&vpath(ctx, rel)).ok()??;
    let (f, _) = fm::split_fm_optional(&tf.text)?;
    fm::get_scalar(&f, "recommendation").filter(|r| !r.is_empty())
}

/// (now, later), each in the order the view prints: now in file order; later by date, then
/// the named triggers in file order.
pub fn items(ctx: &Ctx, doc: &OpenDoc, today: NaiveDate) -> (Vec<Item>, Vec<Item>) {
    let (mut now, mut later): (Vec<Item>, Vec<Item>) = doc
        .loops
        .iter()
        .filter_map(|l| {
            let need = l.need.clone()?;
            let rel = need.detail_rel();
            let item = Item { l: l.clone(), rec: recommendation(ctx, &rel), detail_exists: pyos::isfile(&vpath(ctx, &rel)), need };
            Some(item)
        })
        .partition(|i| i.need.when.is_now(today));
    now.sort_by_key(|i| i.l.n);
    later.sort_by_key(|i| match &i.need.when {
        When::On(d) => (0, Some(*d), i.l.n),
        _ => (1, None, i.l.n),
    });
    (now, later)
}

fn rec_of(i: &Item) -> String {
    i.rec.clone().unwrap_or_else(|| "no recommendation written".to_string())
}

fn view_line(i: &Item) -> String {
    let lead = match &i.need.when {
        When::Now | When::On(_) if i.need.when.is_now(today_date()) => String::new(),
        w => format!("{}: ", w.field()),
    };
    if !i.detail_exists {
        return format!("- {lead}{} · detail file missing: {}", i.l.text, i.need.detail);
    }
    let label = i.l.text.replace('[', r"\[").replace(']', r"\]");
    format!("- {lead}[{label}]({}) · recommend: {}", i.need.detail, rec_of(i))
}

fn view_text(now: &[Item], later: &[Item]) -> String {
    let mut s = String::from(VIEW_HEAD);
    for (title, group) in [("Now", now), ("Later", later)] {
        s.push_str(&format!("\n## {title} ({})\n\n", group.len()));
        if group.is_empty() {
            s.push_str("Nothing.\n");
        }
        for i in group {
            s.push_str(&view_line(i));
            s.push('\n');
        }
    }
    s
}

/// The view as af would write it now; None when there is nothing to show and no view yet.
fn rendered(ctx: &Ctx) -> R<Option<String>> {
    let doc = OpenDoc::load(ctx)?;
    let (now, later) = match &doc {
        Some(d) => items(ctx, d, today_date()),
        None => (Vec::new(), Vec::new()),
    };
    if now.is_empty() && later.is_empty() && !pyos::isfile(&vpath(ctx, VIEW_REL)) {
        return Ok(None);
    }
    Ok(Some(view_text(&now, &later)))
}

/// Rewrite the view when it differs from what open.md and the detail files say.
pub fn render(ctx: &Ctx) -> R<()> {
    let Some(text) = rendered(ctx)? else {
        return Ok(());
    };
    let path = vpath(ctx, VIEW_REL);
    if TextFile::load(&path)?.map(|t| t.text) != Some(text.clone()) {
        TextFile::new(&text).save(&path)?;
    }
    Ok(())
}

/// One line per count, then one per item: what every surface leads with.
pub fn summary(now: usize, later: usize) -> String {
    format!("needs you: {now} now, {later} later ({VIEW_REL})")
}

fn surface_line(i: &Item) -> String {
    format!("- {} · recommend: {} · {}", i.l.text, rec_of(i), i.need.detail_rel())
}

/// The session-start block: the count and the Now items; None when the list is empty.
pub fn bundle_block(ctx: &Ctx, doc: &OpenDoc) -> Option<String> {
    let (now, later) = items(ctx, doc, today_date());
    if now.is_empty() && later.is_empty() {
        return None;
    }
    let mut s = summary(now.len(), later.len());
    for i in &now {
        s.push('\n');
        s.push_str(&surface_line(i));
    }
    Some(s)
}

/// `af brief`: its section (omitted when the list is empty) and its JSON.
pub fn brief_parts(ctx: &Ctx, doc: Option<&OpenDoc>) -> (Option<String>, Value) {
    let (now, later) = match doc {
        Some(d) => items(ctx, d, today_date()),
        None => (Vec::new(), Vec::new()),
    };
    let js = json!({
        "now": now.iter().map(|i| json!({"text": i.l.text, "recommendation": i.rec, "detail": i.need.detail_rel()})).collect::<Vec<_>>(),
        "later": later.iter().map(|i| json!({"text": i.l.text, "when": i.need.when.field(), "recommendation": i.rec, "detail": i.need.detail_rel()})).collect::<Vec<_>>(),
    });
    if now.is_empty() && later.is_empty() {
        return (None, js);
    }
    let mut s = format!("## Needs you ({} now, {} later)", now.len(), later.len());
    for i in &now {
        s.push('\n');
        s.push_str(&surface_line(i));
    }
    (Some(s), js)
}

// ------------------------------------------------------------------ closing

/// Move a closed item's detail file to `needs/closed/`, so the full notes survive and the
/// live folder holds only open items. Returns its new path under `workspace/life/`, or
/// None when the file is already gone.
pub fn archive_detail(ctx: &Ctx, need: &Need) -> R<Option<String>> {
    let from = vpath(ctx, &need.detail_rel());
    if !pyos::isfile(&from) {
        return Ok(None);
    }
    let stem = need.detail.trim_start_matches("needs/").trim_end_matches(".md");
    let mut n = 1;
    let rel = loop {
        let name = if n == 1 { format!("needs/closed/{stem}.md") } else { format!("needs/closed/{stem}-{n}.md") };
        if !pyos::isfile(&vpath(ctx, &format!("{LIFE_REL}/{name}"))) {
            break name;
        }
        n += 1;
    };
    let to = vpath(ctx, &format!("{LIFE_REL}/{rel}"));
    pyos::makedirs(&pyos::dirname(&to))?;
    std::fs::rename(&from, &to).map_err(|e| pyos::os_error(&e, &from))?;
    Ok(Some(rel))
}

// ------------------------------------------------------------------ verbs

#[derive(Subcommand, Debug)]
pub enum NeedsCmd {
    /// Put a decision on the list; without --on or --when it needs him now
    Add {
        /// the decision, as a question
        text: String,
        /// the detail file, needs/<slug>.md under workspace/life/, already written
        #[arg(long)]
        detail: String,
        /// later: it moves to Now on this date (YYYY-MM-DD or +Nd)
        #[arg(long, conflicts_with = "when")]
        on: Option<String>,
        /// later: it waits on this named threshold or event until af needs move
        #[arg(long)]
        when: Option<String>,
        #[arg(long)]
        from: Option<String>,
    },
    /// Close an item (number, detail slug, or text prefix): the month log takes the outcome
    Close {
        target: String,
        #[arg(long)]
        outcome: String,
    },
    /// Change an item's state; a trigger that fired moves it with --now
    Move {
        target: String,
        #[arg(long, conflicts_with_all = ["on", "when"])]
        now: bool,
        #[arg(long, conflicts_with = "when")]
        on: Option<String>,
        #[arg(long)]
        when: Option<String>,
    },
    /// Print the list and refresh the view
    List,
    /// Rewrite workspace/life/needs.md from open.md and the detail files
    Render,
}

pub fn run(ctx: &Ctx, cmd: NeedsCmd) -> R<i32> {
    match cmd {
        NeedsCmd::Add { text, detail, on, when, from } => cmd_add(ctx, &text, &detail, on.as_deref(), when.as_deref(), from.as_deref()),
        NeedsCmd::Close { target, outcome } => cmd_close(ctx, &target, &outcome),
        NeedsCmd::Move { target, now, on, when } => cmd_move(ctx, &target, now, on.as_deref(), when.as_deref()),
        NeedsCmd::List => cmd_list(ctx),
        NeedsCmd::Render => {
            render(ctx)?;
            outln!("af needs render: {VIEW_REL}");
            Ok(0)
        }
    }
}

fn parse_when(on: Option<&str>, when: Option<&str>) -> R<When> {
    if let Some(v) = on {
        return match open::parse_nudge(v, today_date()) {
            Some(d) => Ok(When::On(d)),
            None => die!("--on takes YYYY-MM-DD or +Nd, got '{v}'"),
        };
    }
    if let Some(v) = when {
        let t = life::one_line(v);
        if t.is_empty() || t.contains(" · ") {
            die!("--when needs the threshold or event in a few words, without ' · ', got '{v}'");
        }
        return Ok(When::Trigger(t));
    }
    Ok(When::Now)
}

/// `needs/<slug>.md` from the forms a caller may hold: that, the vault path, or an absolute one.
fn normalize_detail(ctx: &Ctx, v: &str) -> R<String> {
    let p = v.trim().replace('\\', "/");
    let root = format!("{}/", ctx.root.replace('\\', "/"));
    let p = p.strip_prefix(&root).unwrap_or(&p);
    let p = p.strip_prefix("./").unwrap_or(p);
    let p = p.strip_prefix("workspace/life/").unwrap_or(p);
    if !rx(r"\Aneeds/[a-z0-9][a-z0-9-]*\.md\z").is_match(p) {
        die!("--detail takes needs/<kebab-slug>.md under workspace/life/, got '{v}'");
    }
    Ok(p.to_string())
}

pub fn cmd_add(ctx: &Ctx, text: &str, detail: &str, on: Option<&str>, when: Option<&str>, from: Option<&str>) -> R<i32> {
    let text = life::one_line(text);
    if text.is_empty() {
        die!("a needs item needs its question");
    }
    let from = life::one_line(from.unwrap_or(open::DEFAULT_FROM));
    if from.is_empty() {
        die!("--from may not be empty");
    }
    let need = Need { when: parse_when(on, when)?, detail: normalize_detail(ctx, detail)? };
    let rel = need.detail_rel();
    if !pyos::isfile(&vpath(ctx, &rel)) {
        die!("{rel} does not exist; write the detail file first (library/schema/needs-list.md)");
    }
    if recommendation(ctx, &rel).is_none() {
        die!("{rel} has no 'recommendation:' in its frontmatter; add it in a few words (library/schema/needs-list.md)");
    }
    let today = today_date();
    let line = format_line(today, &text, &need, &from);
    let (plain, parsed) = split_need(&line);
    match open::parse_open(&plain) {
        Some((_, t, None, None, f)) if t == text && f == from && parsed.as_ref() == Some(&need) => {}
        _ => die!("the item text breaks the open.md grammar (it may not contain ' · need ', ' · detail ', ' · nudge ', ' · every ', or ' · from: '): {text}"),
    }
    let path = vpath(ctx, OPEN_REL);
    let file = TextFile::load(&path)?.unwrap_or_else(|| TextFile::new(""));
    let mut doc = OpenDoc::parse(path, file);
    if let Some(l) = doc.loops.iter().find(|l| l.need.as_ref().is_some_and(|n| n.detail == need.detail)) {
        die!("{rel} already belongs to open item #{}: {}", l.n, l.text);
    }
    open::insert_in_section(&mut doc.lines, SECTION, &line);
    doc.save()?;
    render(ctx)?;
    outln!("{line}");
    Ok(0)
}

/// The one needs item `target` names: a loop number, a detail slug, or a text prefix.
fn find_item(doc: &OpenDoc, target: &str) -> R<Loop> {
    let t = target.trim();
    let marked = |l: &&Loop| l.need.is_some();
    let by_slug = doc.loops.iter().filter(marked).find(|l| {
        l.need.as_ref().is_some_and(|n| n.detail.trim_start_matches("needs/").trim_end_matches(".md") == t)
    });
    if let Some(l) = by_slug {
        return Ok(l.clone());
    }
    let hit = open::find_target_in(doc, target, |l| l.need.is_some(), "needs item")?;
    Ok(hit)
}

fn cmd_close(ctx: &Ctx, target: &str, outcome: &str) -> R<i32> {
    let mut doc = match OpenDoc::load(ctx)? {
        Some(d) => d,
        None => die!("{OPEN_REL} not found"),
    };
    let hit = find_item(&doc, target)?;
    open::close_loop(ctx, &mut doc, &hit, outcome, false, "af needs close")
}

fn cmd_move(ctx: &Ctx, target: &str, now: bool, on: Option<&str>, when: Option<&str>) -> R<i32> {
    if !now && on.is_none() && when.is_none() {
        die!("af needs move needs --now, --on <date>, or --when <trigger>");
    }
    let new = parse_when(on, when)?;
    let mut doc = match OpenDoc::load(ctx)? {
        Some(d) => d,
        None => die!("{OPEN_REL} not found"),
    };
    let hit = find_item(&doc, target)?;
    let Some(need) = hit.need.clone() else {
        die!("#{} is not a needs item", hit.n);
    };
    let was = need.when.field();
    let moved = Need { when: new, detail: need.detail };
    let field = moved.when.field();
    doc.lines[hit.line_idx] = format_line(hit.opened, &hit.text, &moved, &hit.from);
    doc.save()?;
    let rel = life::append_log(ctx, "redated", &format!("{} → need {field} (was need {was})", hit.text))?;
    render(ctx)?;
    outln!("af needs move: #{} {} → need {field} (was need {was}; logged in {rel})", hit.n, hit.text);
    Ok(0)
}

fn cmd_list(ctx: &Ctx) -> R<i32> {
    render(ctx)?;
    let doc = OpenDoc::load(ctx)?;
    let (now, later) = match &doc {
        Some(d) => items(ctx, d, today_date()),
        None => (Vec::new(), Vec::new()),
    };
    outln!("{}", summary(now.len(), later.len()));
    for i in &now {
        outln!("  #{} {} · recommend: {} · {}", i.l.n, i.l.text, rec_of(i), i.need.detail_rel());
    }
    for i in &later {
        outln!("  #{} {}: {} · recommend: {} · {}", i.l.n, i.need.when.field(), i.l.text, rec_of(i), i.need.detail_rel());
    }
    Ok(0)
}

