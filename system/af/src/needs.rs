//! The needs list: what main needs the operator to decide. An item is a marked loop in
//! `workspace/life/open.md`, so open.md stays the one truth for reminders:
//!
//! `- [ ] 2026-11-05 · which plan to take · need now · detail needs/plan-choice.md · from: main`
//! `... · need on 2026-12-01 · detail needs/x.md · from: main`
//! `... · need when the quote arrives · detail needs/y.md · from: main`
//!
//! `workspace/life/needs/<slug>.md` holds the full detail and the one-line recommendation.
//! `workspace/life/needs.md` is a view generated from those two, never edited by hand: Now,
//! Do (the plain due loops that are his to act on), and Later. Every read or write of the
//! loops rewrites it, so a date that passes reaches it with no one touching open.md.

