//! The needs list: what main needs the operator to decide. An item is a marked loop in
//! `workspace/life/open.md`, so open.md stays the one truth for reminders, and the line
//! carries the decision's recommendation, options and reason:
//!
//! `- [ ] 2026-11-05 · which plan to take · need now · rec: the cheaper plan · options: a) the cheaper plan; b) stay · why: you use 3 GB a month · more: knowledge/phone.md#plans · from: main`
//! `... · need on 2026-12-01 · rec: renew · from: main`
//! `... · need when the quote arrives · rec: wait · from: main`
//!
//! `rec`, `options`, `why` and `more` come in that order, before `from:`. A line written the
//! old way (`· detail needs/<slug>.md`, the recommendation in that file's frontmatter) still
//! parses and works. `workspace/life/needs.md` is a view generated from the lines, never
//! edited by hand: Now, Do (the plain due loops that are his to act on), and Later. Every
//! read or write of the loops rewrites it, so a date that passes reaches it with no one
//! touching open.md.

