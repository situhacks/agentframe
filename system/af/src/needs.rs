#[derive(Subcommand, Debug)]
pub enum NeedsCmd {
    /// Put a decision on the list; without --on or --when it needs him now
    Add {
        /// the decision, as a question
        text: String,
        /// the recommendation, 12 words or fewer
        #[arg(long)]
        rec: Option<String>,
        /// an option, 30 words or fewer without ';' (repeat for up to 5); af writes the letters
        #[arg(long = "option")]
        options: Vec<String>,
        /// why, 60 words or fewer
        #[arg(long)]
        why: Option<String>,
        /// an existing document that holds more: a path under workspace/life/ or the vault root, with an optional #anchor
        #[arg(long)]
        more: Option<String>,
        /// the old form: a detail file, needs/<slug>.md under workspace/life/, already written
        #[arg(long)]
        detail: Option<String>,
        /// later: it moves to Now on this date (YYYY-MM-DD or +Nd)
        #[arg(long, conflicts_with = "when")]
        on: Option<String>,
        /// later: it waits on this named threshold or event until af needs move
        #[arg(long)]
        when: Option<String>,
        #[arg(long)]
        from: Option<String>,
    },
    /// Change the fields of an open item in place; fields not named stay as they are
    Set {
        /// number, old detail slug, or text prefix
        target: String,
        #[arg(long)]
        rec: Option<String>,
        /// replaces the whole option list (repeat for up to 5; one empty value clears it)
        #[arg(long = "option")]
        options: Vec<String>,
        /// an empty value clears it
        #[arg(long)]
        why: Option<String>,
        /// an empty value clears it
        #[arg(long)]
        more: Option<String>,
        /// remove the old detail file reference and move that file to needs/closed/
        #[arg(long)]
        drop_detail: bool,
    },
    /// Close an item (number, old detail slug, or text prefix): the month log takes the outcome
    Close {
        target: String,
        #[arg(long)]
        outcome: String,
    },
    /// Change an item's state; a trigger that fired moves it with --now
    Move {
        target: String,
        #[arg(long, conflicts_with_all = ["on", "when"])]
        now: bool,
        #[arg(long, conflicts_with = "when")]
        on: Option<String>,
        #[arg(long)]
        when: Option<String>,
    },
    /// Print the list and refresh the view
    List,
    /// Rewrite workspace/life/needs.md from open.md and the old detail files
    Render,
}

pub fn run(ctx: &Ctx, cmd: NeedsCmd) -> R<i32> {
    match cmd {
        NeedsCmd::Add { text, rec, options, why, more, detail, on, when, from } => {
            let a = NewNeed {
                text: &text,
                rec: rec.as_deref(),
                options: &options,
                why: why.as_deref(),
                more: more.as_deref(),
                detail: detail.as_deref(),
                on: on.as_deref(),
                when: when.as_deref(),
                from: from.as_deref(),
            };
            cmd_add(ctx, &a)
        }
        NeedsCmd::Set { target, rec, options, why, more, drop_detail } => {
            let s = Changes { rec: rec.as_deref(), options: &options, why: why.as_deref(), more: more.as_deref(), drop_detail };
            cmd_set(ctx, &target, &s)
        }
        NeedsCmd::Close { target, outcome } => cmd_close(ctx, &target, &outcome),
        NeedsCmd::Move { target, now, on, when } => cmd_move(ctx, &target, now, on.as_deref(), when.as_deref()),
        NeedsCmd::List => cmd_list(ctx),
        NeedsCmd::Render => {
            render(ctx)?;
            outln!("af needs render: {VIEW_REL}");
            Ok(0)
        }
    }
}

fn parse_when(on: Option<&str>, when: Option<&str>) -> R<When> {
    if let Some(v) = on {
        return match open::parse_nudge(v, today_date()) {
            Some(d) => Ok(When::On(d)),
            None => die!("--on takes YYYY-MM-DD or +Nd, got '{v}'"),
        };
    }
    if let Some(v) = when {
        let t = life::one_line(v);
        if t.is_empty() || t.contains(" · ") {
            die!("--when needs the threshold or event in a few words, without ' · ', got '{v}'");
        }
        return Ok(When::Trigger(t));
    }
    Ok(When::Now)
}

/// `needs/<slug>.md` from the forms a caller may hold: that, the vault path, or an absolute one.
fn normalize_detail(ctx: &Ctx, v: &str) -> R<String> {
    let p = v.trim().replace('\\', "/");
    let root = format!("{}/", ctx.root.replace('\\', "/"));
    let p = p.strip_prefix(&root).unwrap_or(&p);
    let p = p.strip_prefix("./").unwrap_or(p);
    let p = p.strip_prefix("workspace/life/").unwrap_or(p);
    if !rx(r"\Aneeds/[a-z0-9][a-z0-9-]*\.md\z").is_match(p) {
        die!("--detail takes needs/<kebab-slug>.md under workspace/life/, got '{v}'");
    }
    Ok(p.to_string())
}

/// What `af needs add` is given.
pub struct NewNeed<'a> {
    pub text: &'a str,
    pub rec: Option<&'a str>,
    pub options: &'a [String],
    pub why: Option<&'a str>,
    pub more: Option<&'a str>,
    /// The old form.
    pub detail: Option<&'a str>,
    pub on: Option<&'a str>,
    pub when: Option<&'a str>,
    pub from: Option<&'a str>,
}

/// The line must read back as the same text, source and need, or it would not parse as
/// written.
fn verify_line(line: &str, text: &str, need: &Need, from: &str) -> R<()> {
    let (plain, parsed) = split_need(line);
    match open::parse_open(&plain) {
        Some((_, t, None, None, f)) if t == text && f == from && parsed.as_ref() == Some(need) => Ok(()),
        _ => die!("the item breaks the open.md grammar (the question or a field may not contain ' · ' or one of ' · need ', ' · detail ', ' · rec: ', ' · options: ', ' · why: ', ' · more: ', ' · nudge ', ' · every ', ' · from: '): {text}"),
    }
}

pub fn cmd_add(ctx: &Ctx, a: &NewNeed) -> R<i32> {
    open::locked(ctx, || cmd_add_unlocked(ctx, a))
}

fn cmd_add_unlocked(ctx: &Ctx, a: &NewNeed) -> R<i32> {
    let text = life::one_line(a.text);
    if text.is_empty() {
        die!("a needs item needs its question");
    }
    for t in [" · need ", " · detail ", " · rec: ", " · options: ", " · why: ", " · more: "] {
        if text.contains(t) {
            die!("the question may not contain '{}' (it is a field separator on the line); reword it: {text}", t.trim());
        }
    }
    let from = life::one_line(a.from.unwrap_or(open::DEFAULT_FROM));
    if from.is_empty() {
        die!("--from may not be empty");
    }
    let mut need = Need::new(parse_when(a.on, a.when)?);
    if let Some(d) = a.detail {
        let detail = normalize_detail(ctx, d)?;
        let rel = format!("{LIFE_REL}/{detail}");
        if !pyos::isfile(&vpath(ctx, &rel)) {
            die!("{rel} does not exist; write the detail file first (library/schema/needs-list.md)");
        }
        if a.rec.is_none() && recommendation(ctx, &rel).is_none() {
            die!("{rel} has no 'recommendation:' in its frontmatter; add it in a few words, or give --rec (library/schema/needs-list.md)");
        }
        need.detail = Some(detail);
        eprintln!("af needs add: --detail is the old form; give --rec, --option, --why and --more instead, and link an existing document for anything longer");
    } else if a.rec.is_none() {
        die!("af needs add needs --rec: the recommendation in 12 words or fewer (library/schema/needs-list.md)");
    }
    need.rec = a.rec.map(check_rec).transpose()?;
    need.options = check_options(a.options)?;
    need.why = a.why.map(check_why).transpose()?.flatten();
    need.more = a.more.map(|m| check_more(ctx, m)).transpose()?.flatten();
    let line = format_line(today_date(), &text, &need, &from);
    verify_line(&line, &text, &need, &from)?;
    let path = vpath(ctx, OPEN_REL);
    let file = TextFile::load(&path)?.unwrap_or_else(|| TextFile::new(""));
    let mut doc = OpenDoc::parse(path, file);
    if let Some(d) = &need.detail {
        if let Some(l) = doc.loops.iter().find(|l| l.need.as_ref().is_some_and(|n| n.detail.as_ref() == Some(d))) {
            die!("{LIFE_REL}/{d} already belongs to open item #{}: {}", l.n, l.text);
        }
    }
    open::insert_in_section(&mut doc.lines, SECTION, &line);
    doc.save(ctx)?;
    outln!("{line}");
    Ok(0)
}

/// What `af needs set` changes; a field not named stays as it is.
pub struct Changes<'a> {
    pub rec: Option<&'a str>,
    /// Given at all, it replaces the whole list.
    pub options: &'a [String],
    pub why: Option<&'a str>,
    pub more: Option<&'a str>,
    pub drop_detail: bool,
}

fn cmd_set(ctx: &Ctx, target: &str, c: &Changes) -> R<i32> {
    open::locked(ctx, || cmd_set_unlocked(ctx, target, c))
}

fn cmd_set_unlocked(ctx: &Ctx, target: &str, c: &Changes) -> R<i32> {
    if c.rec.is_none() && c.options.is_empty() && c.why.is_none() && c.more.is_none() && !c.drop_detail {
        die!("af needs set needs at least one of --rec, --option, --why, --more, --drop-detail");
    }
    let mut doc = match OpenDoc::load(ctx)? {
        Some(d) => d,
        None => die!("{OPEN_REL} not found"),
    };
    let hit = find_item(&doc, target)?;
    let Some(old) = hit.need.clone() else {
        die!("#{} is not a needs item", hit.n);
    };
    let mut need = old.clone();
    if let Some(r) = c.rec {
        need.rec = Some(check_rec(r)?);
    }
    if !c.options.is_empty() {
        need.options = check_options(c.options)?;
    }
    if let Some(w) = c.why {
        need.why = check_why(w)?;
    }
    if let Some(m) = c.more {
        need.more = check_more(ctx, m)?;
    }
    let mut archive = None;
    if c.drop_detail {
        if need.detail.is_none() {
            die!("#{} {} has no old detail file to drop", hit.n, hit.text);
        }
        if need.rec.is_none() {
            die!("--drop-detail needs a recommendation on the line, so the file's is not lost: add --rec \"<a few words>\"");
        }
        archive = archive_target(ctx, &old);
        need.detail = None;
    }
    let line = format_line(hit.opened, &hit.text, &need, &hit.from);
    verify_line(&line, &hit.text, &need, &hit.from)?;
    // The file moves first, so a failed move leaves the line naming it; a failed write puts it back.
    if let (Some(to), Some(from_rel)) = (&archive, old.detail_rel()) {
        if !move_file(ctx, &from_rel, to) {
            die!("{from_rel} could not move to {LIFE_REL}/{to}; nothing was changed and the item still names it. Fix what blocks the move and run it again");
        }
    }
    doc.lines[hit.line_idx] = line.clone();
    if let Err(e) = doc.save(ctx) {
        if let (Some(to), Some(from_rel)) = (&archive, old.detail_rel()) {
            let _ = std::fs::rename(vpath(ctx, &format!("{LIFE_REL}/{to}")), vpath(ctx, &from_rel));
        }
        return Err(e);
    }
    outln!("{line}");
    if c.drop_detail {
        let (what, kept) = match &archive {
            Some(to) => (format!("moved to {LIFE_REL}/{to}"), format!(" (detail: {to})")),
            None => ("the file was already gone".to_string(), String::new()),
        };
        let rel = life::append_log(ctx, "folded", &format!("{} → old detail file folded into the line{kept}", hit.text))?;
        outln!("af needs set: #{} {} → detail file folded into the line; {what} (logged in {rel})", hit.n, hit.text);
    }
    Ok(0)
}

/// The one needs item `target` names: a loop number, an old detail slug, or a text prefix.
fn find_item(doc: &OpenDoc, target: &str) -> R<Loop> {
    let t = target.trim();
    let marked = |l: &&Loop| l.need.is_some();
    let by_slug = doc
        .loops
        .iter()
        .filter(marked)
        .filter(|_| t.parse::<usize>().is_err())
        .find(|l| l.need.as_ref().and_then(|n| n.slug()) == Some(t));
    if let Some(l) = by_slug {
        return Ok(l.clone());
    }
    let hit = open::find_target_in(doc, target, |l| l.need.is_some(), "needs item")?;
    Ok(hit)
}

fn cmd_close(ctx: &Ctx, target: &str, outcome: &str) -> R<i32> {
    open::locked(ctx, || cmd_close_unlocked(ctx, target, outcome))
}

fn cmd_close_unlocked(ctx: &Ctx, target: &str, outcome: &str) -> R<i32> {
    let mut doc = match OpenDoc::load(ctx)? {
        Some(d) => d,
        None => die!("{OPEN_REL} not found"),
    };
    let hit = find_item(&doc, target)?;
    open::close_loop(ctx, &mut doc, &hit, outcome, false, "af needs close")
}

fn cmd_move(ctx: &Ctx, target: &str, now: bool, on: Option<&str>, when: Option<&str>) -> R<i32> {
    open::locked(ctx, || cmd_move_unlocked(ctx, target, now, on, when))
}

fn cmd_move_unlocked(ctx: &Ctx, target: &str, now: bool, on: Option<&str>, when: Option<&str>) -> R<i32> {
    if !now && on.is_none() && when.is_none() {
        die!("af needs move needs --now, --on <date>, or --when <trigger>");
    }
    let new = parse_when(on, when)?;
    let mut doc = match OpenDoc::load(ctx)? {
        Some(d) => d,
        None => die!("{OPEN_REL} not found"),
    };
    let hit = find_item(&doc, target)?;
    let Some(need) = hit.need.clone() else {
        die!("#{} is not a needs item", hit.n);
    };
    let was = need.when.field();
    let moved = Need { when: new, ..need };
    let field = moved.when.field();
    doc.lines[hit.line_idx] = format_line(hit.opened, &hit.text, &moved, &hit.from);
    doc.save(ctx)?;
    let rel = life::append_log(ctx, "redated", &format!("{} → need {field} (was need {was})", hit.text))?;
    outln!("af needs move: #{} {} → need {field} (was need {was}; logged in {rel})", hit.n, hit.text);
    Ok(0)
}

fn cmd_list(ctx: &Ctx) -> R<i32> {
    let doc = OpenDoc::load(ctx)?;
    let lists = Lists::of(ctx, doc.as_ref());
    outln!("{}", summary(&lists));
    for i in &lists.now {
        outln!("  #{} {} · recommend: {}{}", i.l.n, i.l.text, rec_of(i), link_suffix(i));
    }
    for l in &lists.todo {
        outln!("  #{} {}", l.n, todo_line(l));
    }
    for i in &lists.later {
        outln!("  #{} {}: {} · recommend: {}{}", i.l.n, i.need.when.field(), i.l.text, rec_of(i), link_suffix(i));
    }
    Ok(0)
}

