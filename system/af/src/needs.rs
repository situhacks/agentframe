/// Where a closed item's detail file goes under `workspace/life/`, so the full notes survive
/// and the live folder holds only open items; None when the file is already gone.
pub fn archive_target(ctx: &Ctx, need: &Need) -> Option<String> {
    if !pyos::isfile(&vpath(ctx, &need.detail_rel())) {
        return None;
    }
    let stem = need.detail.trim_start_matches("needs/").trim_end_matches(".md");
    let mut n = 1;
    let rel = loop {
        let name = if n == 1 { format!("needs/closed/{stem}.md") } else { format!("needs/closed/{stem}-{n}.md") };
        if !pyos::isfile(&vpath(ctx, &format!("{LIFE_REL}/{name}"))) {
            break name;
        }
        n += 1;
    };
    Some(rel)
}

/// The last step of a close, after the log and the line: a failure names the file to move.
pub fn move_detail(ctx: &Ctx, need: &Need, rel: &str) -> R<()> {
    let (from, to) = (vpath(ctx, &need.detail_rel()), vpath(ctx, &format!("{LIFE_REL}/{rel}")));
    let moved = pyos::makedirs(&pyos::dirname(&to)).is_ok() && std::fs::rename(&from, &to).is_ok();
    if !moved {
        die!("the item is closed and logged, but {} could not move to {rel}; move it by hand", need.detail_rel());
    }
    Ok(())
}

