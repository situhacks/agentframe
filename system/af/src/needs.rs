/// For an old-style item: a missing detail file, a detail file with no open item, a detail
/// file without its recommendation (when the line has none), a detail file two items share.
/// For any item: a field over its cap, and a `more:` document that is gone. And a view af
/// could not rewrite. The note counts the open items that still keep an old detail file.
pub fn doctor_checks(ctx: &Ctx) -> R<(Vec<String>, Vec<String>)> {
    let (mut issues, mut notes) = (Vec::new(), Vec::new());
    let doc = OpenDoc::load(ctx)?;
    let marked: Vec<(&Loop, &Need)> =
        doc.iter().flat_map(|d| d.loops.iter()).filter_map(|l| l.need.as_ref().map(|n| (l, n))).collect();

    let mut seen: Vec<&str> = Vec::new();
    for (l, n) in &marked {
        if let (Some(rel), Some(detail)) = (n.detail_rel(), n.detail.as_deref()) {
            if !pyos::isfile(&vpath(ctx, &rel)) {
                issues.push(format!(
                    "{OPEN_REL}: needs item '{}' names {rel}, which does not exist; write it, or af needs close the item",
                    l.text
                ));
            } else if n.rec.is_none() && recommendation(ctx, &rel).is_none() {
                issues.push(format!("{rel}: no 'recommendation:' in its frontmatter; add it in a few words (library/schema/needs-list.md)"));
            }
            if seen.contains(&detail) {
                issues.push(format!("{OPEN_REL}: two needs items share {rel}; give each its own detail file"));
            }
            seen.push(detail);
        }
        for p in field_problems(ctx, n) {
            issues.push(format!("{OPEN_REL}: needs item '{}': {p}; fix it with af needs set {} (library/schema/needs-list.md)", l.text, l.n));
        }
    }

    let dir = vpath(ctx, DETAIL_DIR_REL);
    let mut files: Vec<String> = match std::fs::read_dir(&dir) {
        Ok(rd) => rd
            .flatten()
            .filter(|e| e.file_type().map(|t| t.is_file()).unwrap_or(false))
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .filter(|n| n.ends_with(".md"))
            .collect(),
        Err(_) => Vec::new(),
    };
    files.sort();
    for name in files {
        let detail = format!("needs/{name}");
        if !seen.contains(&detail.as_str()) {
            issues.push(format!(
                "{DETAIL_DIR_REL}/{name}: no open needs item names this file; move it to needs/closed/ or delete it"
            ));
        }
    }

    let old = marked.iter().filter(|(_, n)| n.detail.is_some()).count();
    if old > 0 {
        let s = if old == 1 { "item still keeps" } else { "items still keep" };
        notes.push(format!(
            "{OPEN_REL}: {old} open needs {s} an old detail file; fold one in with af needs set <n> --rec \"<a few words>\" --drop-detail"
        ));
    }

    if let Some(text) = rendered(ctx)? {
        if view_on_disk(ctx).as_deref() != Some(text.as_str()) {
            notes.push(format!("{VIEW_REL}: differs from open.md and the old detail files and af could not rewrite it; fix the file, then run af needs render"));
        }
    }
    Ok((issues, notes))
}
