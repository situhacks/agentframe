pub const VIEW_REL: &str = "workspace/life/needs.md";
pub const DETAIL_DIR_REL: &str = "workspace/life/needs";
pub const SECTION: &str = "Decisions needed";
/// A due loop under this heading is someone else's to answer, so it is not his to do.
pub const OTHERS_SECTION: &str = "Waiting on others";
const LIFE_REL: &str = "workspace/life";
const VIEW_HEAD: &str = "# What needs you\n\n<!-- Generated by af from the need lines in open.md; an edit here is overwritten. Change it with af needs. -->\n";

/// The most words each field may hold, and the most options.
pub const REC_WORDS: usize = 12;
pub const OPTION_WORDS: usize = 30;
pub const OPTIONS_MAX: usize = 5;
pub const WHY_WORDS: usize = 60;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum When {
    Now,
    On(NaiveDate),
    Trigger(String),
}

impl When {
    pub fn field(&self) -> String {
        match self {
            When::Now => "now".to_string(),
            When::On(d) => format!("on {}", d.format("%Y-%m-%d")),
            When::Trigger(t) => format!("when {t}"),
        }
    }

    /// Whether it needs him now: a dated item does from its date on, by itself.
    pub fn is_now(&self, today: NaiveDate) -> bool {
        match self {
            When::Now => true,
            When::On(d) => *d <= today,
            When::Trigger(_) => false,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Need {
    pub when: When,
    /// An old-style item's detail file, relative to `workspace/life/`: `needs/<slug>.md`.
    pub detail: Option<String>,
    /// A few words. A line has one unless it is old-style, where the file holds it.
    pub rec: Option<String>,
    /// The option texts, without their letters.
    pub options: Vec<String>,
    pub why: Option<String>,
    /// An existing document, relative to `workspace/life/` or the vault root, with an optional `#anchor`.
    pub more: Option<String>,
}

impl Need {
    /// A need with only its state; the fields are filled in after.
    pub fn new(when: When) -> Need {
        Need { when, detail: None, rec: None, options: Vec::new(), why: None, more: None }
    }

    pub fn detail_rel(&self) -> Option<String> {
        self.detail.as_ref().map(|d| format!("{LIFE_REL}/{d}"))
    }

    /// The slug of an old-style detail file.
    pub fn slug(&self) -> Option<&str> {
        self.detail.as_deref().map(|d| d.trim_start_matches("needs/").trim_end_matches(".md"))
    }
}

/// A value, shortest first: a lazy optional tail, or the value would swallow the fields after it.
const FIELD: &str = r"(\S(?:.*?\S)??)";

/// Lifts the need fields off a loop line: the line without them, and the need. A line whose
/// fields are malformed, out of order, or give neither a `rec:` nor a detail file comes back
/// whole, and `parse_open` refuses its ` · need ` token.
pub fn split_need(line: &str) -> (String, Option<Need>) {
    let re = rx(&format!(
        r"\A(.*) · need (now|on \d{{4}}-\d{{2}}-\d{{2}}|when \S(?:.*?\S)??)(?: · detail (needs/[a-z0-9][a-z0-9-]*\.md))?(?: · rec: {FIELD})?(?: · options: {FIELD})?(?: · why: {FIELD})?(?: · more: {FIELD})? · from: (.*)\z"
    ));
    let Some(c) = re.captures(line) else {
        return (line.to_string(), None);
    };
    if c.get(3).is_none() && c.get(4).is_none() {
        return (line.to_string(), None);
    }
    // A value with a ` · ` in it is a field out of order or a separator in a value: not a need.
    if (3..=7).any(|i| c.get(i).is_some_and(|m| m.as_str().contains(" · "))) {
        return (line.to_string(), None);
    }
    let field = &c[2];
    let when = if field == "now" {
        Some(When::Now)
    } else if let Some(d) = field.strip_prefix("on ") {
        NaiveDate::parse_from_str(d, "%Y-%m-%d").ok().map(When::On)
    } else {
        let t = &field["when ".len()..];
        (!t.contains(" · ")).then(|| When::Trigger(t.to_string()))
    };
    let get = |i: usize| c.get(i).map(|m| m.as_str().to_string());
    let options = get(5).map(|o| o.split("; ").map(strip_letter).collect()).unwrap_or_default();
    match when {
        Some(when) => {
            let need = Need { when, detail: get(3), rec: get(4), options, why: get(6), more: get(7) };
            (format!("{} · from: {}", &c[1], &c[8]), Some(need))
        }
        None => (line.to_string(), None),
    }
}

/// An option without the `a) ` the line writes before it.
fn strip_letter(piece: &str) -> String {
    let re = rx(r"\A[a-z]\) (.*)\z");
    re.captures(piece).map(|c| c[1].to_string()).unwrap_or_else(|| piece.to_string())
}

/// `a) first; b) second`: the letters are af's, in order.
fn options_field(options: &[String]) -> String {
    options.iter().enumerate().map(|(i, o)| format!("{}) {o}", (b'a' + i as u8) as char)).collect::<Vec<_>>().join("; ")
}

pub fn format_line(opened: NaiveDate, text: &str, need: &Need, from: &str) -> String {
    let mut s = format!("- [ ] {} · {text} · need {}", opened.format("%Y-%m-%d"), need.when.field());
    if let Some(d) = &need.detail {
        s.push_str(&format!(" · detail {d}"));
    }
    if let Some(r) = &need.rec {
        s.push_str(&format!(" · rec: {r}"));
    }
    if !need.options.is_empty() {
        s.push_str(&format!(" · options: {}", options_field(&need.options)));
    }
    if let Some(w) = &need.why {
        s.push_str(&format!(" · why: {w}"));
    }
    if let Some(m) = &need.more {
        s.push_str(&format!(" · more: {m}"));
    }
    s.push_str(&format!(" · from: {from}"));
    s
}

// ------------------------------------------------------------------ the fields

fn words(s: &str) -> usize {
    s.split_whitespace().count()
}

/// A value the line can hold: no ` · ` that would cut it in two.
fn check_value(name: &str, v: &str) -> R<()> {
    if v.contains(" · ") || v.starts_with('·') || v.ends_with('·') {
        die!("{name} may not contain ' · ' (it separates the fields on the line); reword it: {v}");
    }
    Ok(())
}

fn check_cap(name: &str, v: &str, cap: usize) -> R<()> {
    let n = words(v);
    if n > cap {
        die!("{name} is {n} words; the cap is {cap}. Shorten it, and link a document with --more for the rest");
    }
    Ok(())
}

/// `--rec`: one line, 1 to 12 words.
fn check_rec(v: &str) -> R<String> {
    let v = life::one_line(v);
    if v.is_empty() {
        die!("--rec needs the recommendation, in a few words");
    }
    check_value("--rec", &v)?;
    check_cap("--rec", &v, REC_WORDS)?;
    Ok(v)
}

/// The `--option` list: up to 5, each 1 to 30 words with no `;`. A lone empty option clears the list.
fn check_options(vs: &[String]) -> R<Vec<String>> {
    if vs.len() == 1 && life::one_line(&vs[0]).is_empty() {
        return Ok(Vec::new());
    }
    if vs.len() > OPTIONS_MAX {
        die!("{} options given; the cap is {OPTIONS_MAX}", vs.len());
    }
    let mut out = Vec::new();
    for raw in vs {
        let v = life::one_line(raw);
        if v.is_empty() {
            die!("--option may not be empty");
        }
        if v.contains(';') {
            die!("--option may not contain ';' (it separates the options on the line); reword it or give two options: {v}");
        }
        check_value("--option", &v)?;
        check_cap("--option", &v, OPTION_WORDS)?;
        out.push(v);
    }
    Ok(out)
}

/// `--why`: one line, up to 60 words; empty clears it.
fn check_why(v: &str) -> R<Option<String>> {
    let v = life::one_line(v);
    if v.is_empty() {
        return Ok(None);
    }
    check_value("--why", &v)?;
    check_cap("--why", &v, WHY_WORDS)?;
    Ok(Some(v))
}

/// `--more`: an existing document, not under `needs/`, relative to `workspace/life/` or the
/// vault root (a path inside the vault is cut back to that); empty clears it. The anchor after
/// `#` is kept as written.
fn check_more(ctx: &Ctx, v: &str) -> R<Option<String>> {
    let v = life::one_line(v).replace('\\', "/");
    if v.is_empty() {
        return Ok(None);
    }
    check_value("--more", &v)?;
    let root = format!("{}/", ctx.root.replace('\\', "/"));
    let p = v.strip_prefix(&root).unwrap_or(&v);
    let (path, anchor) = match p.split_once('#') {
        Some((a, b)) => (a, Some(b)),
        None => (p, None),
    };
    // Not absolute in any form (a root, a drive, a share), and `.` segments are dropped before
    // the check below, so `workspace/life/./needs/a.md` is the path it is.
    let segs: Vec<&str> = path.split('/').filter(|s| *s != ".").collect();
    if path.starts_with('/') || rx(r"\A[A-Za-z]:").is_match(path) || segs.is_empty() || segs.iter().any(|s| s.is_empty() || *s == "..") {
        die!("--more takes a path inside the vault, relative to workspace/life/ or the vault root, got '{v}'");
    }
    let path = segs.join("/");
    let p = match anchor {
        Some(a) => format!("{path}#{a}"),
        None => path.clone(),
    };
    let lower = path.to_lowercase();
    if lower.starts_with("needs/") || lower.starts_with("workspace/life/needs/") {
        die!("--more may not point under workspace/life/needs/ (no file is kept for one decision); link the plan, project file, knowledge page or backlog row that holds the detail, got '{v}'");
    }
    if more_link(ctx, &p).is_none() {
        die!("--more '{v}' does not exist (looked under workspace/life/ and the vault root)");
    }
    Ok(Some(p))
}

/// The link from the view (in `workspace/life/`) to a `more:` document; None when it is missing.
fn more_link(ctx: &Ctx, more: &str) -> Option<String> {
    let path = more.split_once('#').map(|(p, _)| p).unwrap_or(more);
    let link = more.replace(' ', "%20");
    if pyos::isfile(&vpath(ctx, &format!("{LIFE_REL}/{path}"))) {
        Some(link)
    } else if pyos::isfile(&vpath(ctx, path)) {
        Some(format!("../../{link}"))
    } else {
        None
    }
}

/// A `more:` path as a vault-relative one, for a reader that has no base to guess: under
/// `workspace/life/` when it is there, else as written (already from the vault root).
fn more_vault_path(ctx: &Ctx, more: &str) -> String {
    let path = more.split_once('#').map(|(p, _)| p).unwrap_or(more);
    if pyos::isfile(&vpath(ctx, &format!("{LIFE_REL}/{path}"))) {
        format!("{LIFE_REL}/{more}")
    } else {
        more.to_string()
    }
}

/// Text for a block in the view: `<` and `>` escaped wherever they are, so no tag or HTML
/// comment opens, and with `leading` a marker at the start that would make a heading, a list,
/// a rule or a quote. The line in open.md is never escaped; only the view is.
fn esc_block(text: &str, leading: bool) -> String {
    let mut s = text.replace('<', r"\<").replace('>', r"\>");
    if leading {
        if s.starts_with(['#', '-', '+', '*', '=']) {
            s.insert(0, '\\');
        } else if let Some(m) = rx(r"\A\d+[.)]").find(&s) {
            s.insert(m.end() - 1, '\\');
        }
    }
    s
}

/// The problems a line's fields have, one message each: what doctor reports for a hand edit.
fn field_problems(ctx: &Ctx, n: &Need) -> Vec<String> {
    let mut v = Vec::new();
    if let Some(r) = &n.rec {
        if words(r) > REC_WORDS {
            v.push(format!("rec is {} words; the cap is {REC_WORDS}", words(r)));
        }
    }
    if n.options.len() > OPTIONS_MAX {
        v.push(format!("{} options; the cap is {OPTIONS_MAX}", n.options.len()));
    }
    for o in &n.options {
        if words(o) > OPTION_WORDS {
            v.push(format!("an option is {} words; the cap is {OPTION_WORDS}", words(o)));
        }
    }
    if let Some(w) = &n.why {
        if words(w) > WHY_WORDS {
            v.push(format!("why is {} words; the cap is {WHY_WORDS}", words(w)));
        }
    }
    if let Some(m) = &n.more {
        if more_link(ctx, m).is_none() {
            v.push(format!("more: {m} no longer exists"));
        }
    }
    v
}

// ------------------------------------------------------------------ the items

/// A marked loop with what the view prints for it.
pub struct Item {
    pub l: Loop,
    pub need: Need,
    /// The line's `rec:`; for an old-style line without one, the detail file's `recommendation:`.
    /// None when neither is there.
    pub rec: Option<String>,
    /// The More cell: links to `more:` and to an old detail file, or what is missing.
    pub more_cell: String,
}

fn recommendation(ctx: &Ctx, rel: &str) -> Option<String> {
    let tf = TextFile::load(&vpath(ctx, rel)).ok()??;
    let (f, _) = fm::split_fm_optional(&tf.text)?;
    // YAML first, for a block scalar; the line as written when the frontmatter is not strict
    // YAML (an unquoted colon) or the value reads as another type (`yes`).
    let yaml = pyyaml::safe_load(&f, "<unicode string>", false).ok();
    let text = yaml.as_ref().and_then(|v| v.get("recommendation")).and_then(|v| v.as_str()).map(life::one_line);
    let text = text.or_else(|| fm::get_scalar(&f, "recommendation").filter(|r| !rx(r"\A([>|][+-]?\d?[+-]?|~|null)\z").is_match(r)));
    text.filter(|r| !r.is_empty())
}

/// What every surface prints.
pub struct Lists {
    pub now: Vec<Item>,
    /// Plain due loops, oldest first: what `af open due` lists, less the needs items and what
    /// others owe. Main reviews and closes the rest, so what stays here is his to do.
    pub todo: Vec<Loop>,
    pub later: Vec<Item>,
}

impl Lists {
    pub fn of(ctx: &Ctx, doc: Option<&OpenDoc>) -> Lists {
        let today = today_date();
        let Some(doc) = doc else {
            return Lists { now: Vec::new(), todo: Vec::new(), later: Vec::new() };
        };
        let (now, later) = items(ctx, doc, today);
        let todo = doc
            .due(today)
            .into_iter()
            .map(|(l, _)| l)
            .filter(|l| l.need.is_none() && l.top != OTHERS_SECTION && l.section != OTHERS_SECTION)
            .collect();
        Lists { now, todo, later }
    }

    fn is_empty(&self) -> bool {
        self.now.is_empty() && self.todo.is_empty() && self.later.is_empty()
    }
}

/// The More cell: a link to the `more:` document and to an old detail file, or what is wrong
/// with either. Empty when the line has neither.
fn more_cell_of(ctx: &Ctx, need: &Need) -> String {
    let mut parts = Vec::new();
    if let Some(m) = &need.more {
        parts.push(match more_link(ctx, m) {
            Some(link) => format!("[more]({link})"),
            None => format!("missing: {}", cell(m)),
        });
    }
    if let Some(d) = &need.detail {
        let exists = pyos::isfile(&vpath(ctx, &format!("{LIFE_REL}/{d}")));
        parts.push(if exists { format!("[open]({d})") } else { format!("detail file missing: {d}") });
    }
    parts.join(", ")
}

/// (now, later), each in the order the view prints: now in file order; later by date, then
/// the named triggers in file order.
fn items(ctx: &Ctx, doc: &OpenDoc, today: NaiveDate) -> (Vec<Item>, Vec<Item>) {
    let (mut now, mut later): (Vec<Item>, Vec<Item>) = doc
        .loops
        .iter()
        .filter_map(|l| {
            let need = l.need.clone()?;
            let rec = need.rec.clone().or_else(|| need.detail_rel().and_then(|rel| recommendation(ctx, &rel)));
            let more_cell = more_cell_of(ctx, &need);
            Some(Item { l: l.clone(), rec, more_cell, need })
        })
        .partition(|i| i.need.when.is_now(today));
    now.sort_by_key(|i| i.l.n);
    later.sort_by_key(|i| match &i.need.when {
        When::On(d) => (0, Some(*d), i.l.n),
        _ => (1, None, i.l.n),
    });
    (now, later)
}

/// Text fit for a table cell: one line, with a pipe that cannot split the row and no `<` or `>`
/// that opens a tag or an HTML comment. A backslash is escaped too, or one ahead of a pipe
/// would cancel that pipe's escape.
pub fn cell(text: &str) -> String {
    life::one_line(text).replace('\\', r"\\").replace('|', r"\|").replace('<', r"\<").replace('>', r"\>")
}

fn rec_of(i: &Item) -> String {
    i.rec.clone().unwrap_or_else(|| "no recommendation written".to_string())
}

fn now_row(i: &Item) -> Vec<String> {
    vec![cell(&i.l.text), cell(&rec_of(i)), i.more_cell.clone()]
}

fn when_cell(w: &When) -> String {
    match w {
        When::Now => "now".to_string(),
        When::On(d) => d.format("%Y-%m-%d").to_string(),
        When::Trigger(t) => cell(t),
    }
}

fn later_row(i: &Item) -> Vec<String> {
    vec![when_cell(&i.need.when), cell(&i.l.text), cell(&rec_of(i)), i.more_cell.clone()]
}

fn do_row(l: &Loop) -> Vec<String> {
    let due = l.due_on().map(|d| d.format("%Y-%m-%d").to_string()).unwrap_or_default();
    vec![cell(&l.text), due, l.opened.format("%Y-%m-%d").to_string()]
}

fn todo_line(l: &Loop) -> String {
    let due = l.due_on().map(|d| d.format("%Y-%m-%d").to_string()).unwrap_or_default();
    format!("{} · due {due}", l.text)
}

fn table_row(cells: &[String]) -> String {
    format!("| {} |\n", cells.join(" | "))
}

/// The block under a table for an item with options or a reason: its question, the
/// recommendation, the lettered options, then the reason. None for an item with neither.
fn block(i: &Item) -> Option<String> {
    if i.need.options.is_empty() && i.need.why.is_none() {
        return None;
    }
    let rec = rec_of(i);
    let stop = if rec.ends_with(['.', '!', '?']) { "" } else { "." };
    let mut s = format!("**{}** Recommended: {}{stop}\n", esc_block(&life::one_line(&i.l.text), false), esc_block(&rec, false));
    for (n, o) in i.need.options.iter().enumerate() {
        s.push_str(&format!("- {}) {}\n", (b'a' + n as u8) as char, esc_block(o, true)));
    }
    if let Some(w) = &i.need.why {
        s.push_str(&format!("\n{}\n", esc_block(w, true)));
    }
    Some(s)
}

/// A section: its heading with the count, then its table and the blocks under it, or
/// `Nothing.` when it has no rows.
fn section(title: &str, head: &[&str], rows: Vec<Vec<String>>, blocks: Vec<String>) -> String {
    let mut body = String::new();
    if rows.is_empty() {
        body.push_str("Nothing.\n");
    } else {
        body.push_str(&format!("| {} |\n|{}\n", head.join(" | "), "---|".repeat(head.len())));
        rows.iter().for_each(|r| body.push_str(&table_row(r)));
        if !blocks.is_empty() {
            body.push('\n');
            body.push_str(&blocks.join("\n"));
        }
    }
    format!("\n## {title} ({})\n\n{body}", rows.len())
}

fn view_text(lists: &Lists) -> String {
    let mut s = String::from(VIEW_HEAD);
    let now_blocks = lists.now.iter().filter_map(block).collect();
    s.push_str(&section("Now", &["Decision", "Recommendation", "More"], lists.now.iter().map(now_row).collect(), now_blocks));
    s.push_str(&section("Do", &["To do", "Due", "Waiting since"], lists.todo.iter().map(do_row).collect(), Vec::new()));
    let later_blocks = lists.later.iter().filter_map(block).collect();
    s.push_str(&section("Later", &["When", "Decision", "Recommendation", "More"], lists.later.iter().map(later_row).collect(), later_blocks));
    s
}

/// The view as af would write it now; None when there is no open.md.
fn rendered(ctx: &Ctx) -> R<Option<String>> {
    let doc = OpenDoc::load_raw(ctx)?;
    Ok(doc.map(|d| view_text(&Lists::of(ctx, Some(&d)))))
}

/// The view on disk, whatever its encoding; None when it cannot be read as a file.
fn view_on_disk(ctx: &Ctx) -> Option<String> {
    let bytes = std::fs::read(vpath(ctx, VIEW_REL)).ok()?;
    Some(String::from_utf8_lossy(&bytes).replace("\r\n", "\n"))
}

/// Rewrite the view when it differs from what open.md and the old detail files say.
pub fn render(ctx: &Ctx) -> R<()> {
    let Some(text) = rendered(ctx)? else {
        return Ok(());
    };
    if view_on_disk(ctx).as_deref() != Some(text.as_str()) {
        TextFile::new(&text).save(&vpath(ctx, VIEW_REL))?;
    }
    Ok(())
}

/// `render` for a verb whose job is the loops: a view it cannot write never stops the verb,
/// and `af doctor` reports it.
pub fn refresh(ctx: &Ctx) {
    let _ = render(ctx);
}

/// The one line a reply to him ends with, and what every surface leads with.
pub fn summary(lists: &Lists) -> String {
    let (now, todo, later) = (lists.now.len(), lists.todo.len(), lists.later.len());
    if now == 0 && todo == 0 {
        return format!("needs you: none now, {later} later ({VIEW_REL})");
    }
    format!("needs you: {now} now, {todo} to do, {later} later ({VIEW_REL})")
}

/// ` · <where>` for what an item links: its old detail file, else its `more:` document.
fn link_suffix(i: &Item) -> String {
    match i.need.detail_rel().or_else(|| i.need.more.clone()) {
        Some(p) => format!(" · {p}"),
        None => String::new(),
    }
}

fn surface_line(i: &Item) -> String {
    format!("- {} · recommend: {}{}", i.l.text, rec_of(i), link_suffix(i))
}

/// The session-start block: the count and the Now items. The due list above it in the
/// bundle already prints what is under Do.
pub fn bundle_block(ctx: &Ctx, doc: &OpenDoc) -> String {
    let lists = Lists::of(ctx, Some(doc));
    let mut s = summary(&lists);
    for i in &lists.now {
        s.push('\n');
        s.push_str(&surface_line(i));
    }
    s
}

/// `af brief`: its section (omitted when the list is empty) and its JSON.
pub fn brief_parts(ctx: &Ctx, doc: Option<&OpenDoc>) -> (Option<String>, Value) {
    let lists = Lists::of(ctx, doc);
    let (now, later) = (&lists.now, &lists.later);
    let js = json!({
        "now": now.iter().map(|i| json!({"text": i.l.text, "recommendation": i.rec, "detail": i.need.detail_rel(), "more": i.need.more.as_ref().map(|m| more_vault_path(ctx, m))})).collect::<Vec<_>>(),
        "do": lists.todo.iter().map(|l| json!({"text": l.text, "due": l.due_on().map(|d| d.format("%Y-%m-%d").to_string())})).collect::<Vec<_>>(),
        "later": later.iter().map(|i| json!({"text": i.l.text, "when": i.need.when.field(), "recommendation": i.rec, "detail": i.need.detail_rel(), "more": i.need.more.as_ref().map(|m| more_vault_path(ctx, m))})).collect::<Vec<_>>(),
    });
    if lists.is_empty() {
        return (None, js);
    }
    let mut s = format!("## Needs you ({} now, {} to do, {} later)", now.len(), lists.todo.len(), later.len());
    for i in now {
        s.push('\n');
        s.push_str(&surface_line(i));
    }
    (Some(s), js)
}

// ------------------------------------------------------------------ closing

/// Where a closed item's old detail file goes under `workspace/life/`, so the full notes
/// survive and the live folder holds only open items; None when the item has no detail file
/// or it is already gone.
pub fn archive_target(ctx: &Ctx, need: &Need) -> Option<String> {
    let rel = need.detail_rel()?;
    if !pyos::isfile(&vpath(ctx, &rel)) {
        return None;
    }
    let stem = need.slug()?;
    let mut n = 1;
    let rel = loop {
        let name = if n == 1 { format!("needs/closed/{stem}.md") } else { format!("needs/closed/{stem}-{n}.md") };
        if !pyos::isfile(&vpath(ctx, &format!("{LIFE_REL}/{name}"))) {
            break name;
        }
        n += 1;
    };
    Some(rel)
}

/// The last step of a close, after the log and the line: a failure names the file to move.
pub fn move_detail(ctx: &Ctx, need: &Need, rel: &str) -> R<()> {
    let Some(from_rel) = need.detail_rel() else {
        return Ok(());
    };
    if !move_file(ctx, &from_rel, rel) {
        die!("the item is closed and logged, but {from_rel} could not move to {rel}; move it by hand");
    }
    Ok(())
}

/// Moves a file under the vault to `rel` (under `workspace/life/`); false when it could not.
fn move_file(ctx: &Ctx, from_rel: &str, rel: &str) -> bool {
    let (from, to) = (vpath(ctx, from_rel), vpath(ctx, &format!("{LIFE_REL}/{rel}")));
    pyos::makedirs(&pyos::dirname(&to)).is_ok() && std::fs::rename(&from, &to).is_ok()
}

