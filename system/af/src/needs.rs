#[derive(Subcommand, Debug)]
pub enum NeedsCmd {
    /// Put a decision on the list; without --on or --when it needs him now
    Add {
        /// the decision, as a question
        text: String,
        /// the detail file, needs/<slug>.md under workspace/life/, already written
        #[arg(long)]
        detail: String,
        /// later: it moves to Now on this date (YYYY-MM-DD or +Nd)
        #[arg(long, conflicts_with = "when")]
        on: Option<String>,
        /// later: it waits on this named threshold or event until af needs move
        #[arg(long)]
        when: Option<String>,
        #[arg(long)]
        from: Option<String>,
    },
    /// Close an item (number, detail slug, or text prefix): the month log takes the outcome
    Close {
        target: String,
        #[arg(long)]
        outcome: String,
    },
    /// Change an item's state; a trigger that fired moves it with --now
    Move {
        target: String,
        #[arg(long, conflicts_with_all = ["on", "when"])]
        now: bool,
        #[arg(long, conflicts_with = "when")]
        on: Option<String>,
        #[arg(long)]
        when: Option<String>,
    },
    /// Print the list and refresh the view
    List,
    /// Rewrite workspace/life/needs.md from open.md and the detail files
    Render,
}

pub fn run(ctx: &Ctx, cmd: NeedsCmd) -> R<i32> {
    match cmd {
        NeedsCmd::Add { text, detail, on, when, from } => cmd_add(ctx, &text, &detail, on.as_deref(), when.as_deref(), from.as_deref()),
        NeedsCmd::Close { target, outcome } => cmd_close(ctx, &target, &outcome),
        NeedsCmd::Move { target, now, on, when } => cmd_move(ctx, &target, now, on.as_deref(), when.as_deref()),
        NeedsCmd::List => cmd_list(ctx),
        NeedsCmd::Render => {
            render(ctx)?;
            outln!("af needs render: {VIEW_REL}");
            Ok(0)
        }
    }
}

fn parse_when(on: Option<&str>, when: Option<&str>) -> R<When> {
    if let Some(v) = on {
        return match open::parse_nudge(v, today_date()) {
            Some(d) => Ok(When::On(d)),
            None => die!("--on takes YYYY-MM-DD or +Nd, got '{v}'"),
        };
    }
    if let Some(v) = when {
        let t = life::one_line(v);
        if t.is_empty() || t.contains(" · ") {
            die!("--when needs the threshold or event in a few words, without ' · ', got '{v}'");
        }
        return Ok(When::Trigger(t));
    }
    Ok(When::Now)
}

/// `needs/<slug>.md` from the forms a caller may hold: that, the vault path, or an absolute one.
fn normalize_detail(ctx: &Ctx, v: &str) -> R<String> {
    let p = v.trim().replace('\\', "/");
    let root = format!("{}/", ctx.root.replace('\\', "/"));
    let p = p.strip_prefix(&root).unwrap_or(&p);
    let p = p.strip_prefix("./").unwrap_or(p);
    let p = p.strip_prefix("workspace/life/").unwrap_or(p);
    if !rx(r"\Aneeds/[a-z0-9][a-z0-9-]*\.md\z").is_match(p) {
        die!("--detail takes needs/<kebab-slug>.md under workspace/life/, got '{v}'");
    }
    Ok(p.to_string())
}

pub fn cmd_add(ctx: &Ctx, text: &str, detail: &str, on: Option<&str>, when: Option<&str>, from: Option<&str>) -> R<i32> {
    open::locked(ctx, || cmd_add_unlocked(ctx, text, detail, on, when, from))
}

fn cmd_add_unlocked(ctx: &Ctx, text: &str, detail: &str, on: Option<&str>, when: Option<&str>, from: Option<&str>) -> R<i32> {
    let text = life::one_line(text);
    if text.is_empty() {
        die!("a needs item needs its question");
    }
    let from = life::one_line(from.unwrap_or(open::DEFAULT_FROM));
    if from.is_empty() {
        die!("--from may not be empty");
    }
    let need = Need { when: parse_when(on, when)?, detail: normalize_detail(ctx, detail)? };
    let rel = need.detail_rel();
    if !pyos::isfile(&vpath(ctx, &rel)) {
        die!("{rel} does not exist; write the detail file first (library/schema/needs-list.md)");
    }
    if recommendation(ctx, &rel).is_none() {
        die!("{rel} has no 'recommendation:' in its frontmatter; add it in a few words (library/schema/needs-list.md)");
    }
    let today = today_date();
    let line = format_line(today, &text, &need, &from);
    let (plain, parsed) = split_need(&line);
    match open::parse_open(&plain) {
        Some((_, t, None, None, f)) if t == text && f == from && parsed.as_ref() == Some(&need) => {}
        _ => die!("the item text breaks the open.md grammar (it may not contain ' · need ', ' · detail ', ' · nudge ', ' · every ', or ' · from: '): {text}"),
    }
    let path = vpath(ctx, OPEN_REL);
    let file = TextFile::load(&path)?.unwrap_or_else(|| TextFile::new(""));
    let mut doc = OpenDoc::parse(path, file);
    if let Some(l) = doc.loops.iter().find(|l| l.need.as_ref().is_some_and(|n| n.detail == need.detail)) {
        die!("{rel} already belongs to open item #{}: {}", l.n, l.text);
    }
    open::insert_in_section(&mut doc.lines, SECTION, &line);
    doc.save(ctx)?;
    outln!("{line}");
    Ok(0)
}

/// The one needs item `target` names: a loop number, a detail slug, or a text prefix.
fn find_item(doc: &OpenDoc, target: &str) -> R<Loop> {
    let t = target.trim();
    let marked = |l: &&Loop| l.need.is_some();
    let by_slug = doc.loops.iter().filter(marked).filter(|_| t.parse::<usize>().is_err()).find(|l| {
        l.need.as_ref().is_some_and(|n| n.detail.trim_start_matches("needs/").trim_end_matches(".md") == t)
    });
    if let Some(l) = by_slug {
        return Ok(l.clone());
    }
    let hit = open::find_target_in(doc, target, |l| l.need.is_some(), "needs item")?;
    Ok(hit)
}

fn cmd_close(ctx: &Ctx, target: &str, outcome: &str) -> R<i32> {
    open::locked(ctx, || cmd_close_unlocked(ctx, target, outcome))
}

fn cmd_close_unlocked(ctx: &Ctx, target: &str, outcome: &str) -> R<i32> {
    let mut doc = match OpenDoc::load(ctx)? {
        Some(d) => d,
        None => die!("{OPEN_REL} not found"),
    };
    let hit = find_item(&doc, target)?;
    open::close_loop(ctx, &mut doc, &hit, outcome, false, "af needs close")
}

fn cmd_move(ctx: &Ctx, target: &str, now: bool, on: Option<&str>, when: Option<&str>) -> R<i32> {
    open::locked(ctx, || cmd_move_unlocked(ctx, target, now, on, when))
}

fn cmd_move_unlocked(ctx: &Ctx, target: &str, now: bool, on: Option<&str>, when: Option<&str>) -> R<i32> {
    if !now && on.is_none() && when.is_none() {
        die!("af needs move needs --now, --on <date>, or --when <trigger>");
    }
    let new = parse_when(on, when)?;
    let mut doc = match OpenDoc::load(ctx)? {
        Some(d) => d,
        None => die!("{OPEN_REL} not found"),
    };
    let hit = find_item(&doc, target)?;
    let Some(need) = hit.need.clone() else {
        die!("#{} is not a needs item", hit.n);
    };
    let was = need.when.field();
    let moved = Need { when: new, detail: need.detail };
    let field = moved.when.field();
    doc.lines[hit.line_idx] = format_line(hit.opened, &hit.text, &moved, &hit.from);
    doc.save(ctx)?;
    let rel = life::append_log(ctx, "redated", &format!("{} → need {field} (was need {was})", hit.text))?;
    outln!("af needs move: #{} {} → need {field} (was need {was}; logged in {rel})", hit.n, hit.text);
    Ok(0)
}

fn cmd_list(ctx: &Ctx) -> R<i32> {
    let doc = OpenDoc::load(ctx)?;
    let lists = Lists::of(ctx, doc.as_ref());
    outln!("{}", summary(&lists));
    for i in &lists.now {
        outln!("  #{} {} · recommend: {} · {}", i.l.n, i.l.text, rec_of(i), i.need.detail_rel());
    }
    for l in &lists.todo {
        outln!("  #{} {}", l.n, todo_line(l));
    }
    for i in &lists.later {
        outln!("  #{} {}: {} · recommend: {} · {}", i.l.n, i.need.when.field(), i.l.text, rec_of(i), i.need.detail_rel());
    }
    Ok(0)
}

